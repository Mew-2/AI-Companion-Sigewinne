def _chitchat_slice(start: int, count: int):
    """从闲聊池按旋转方式取一段，保证不同用例的噪声构成不同。"""
    n = len(CHITCHAT)
    return [CHITCHAT[(start + i) % n] for i in range(count)]


def _noise(start: int, count: int) -> list[dict]:
    return [
        {"fact": f, "keywords": kw, "importance": imp}
        for f, kw, imp in _chitchat_slice(start, count)
    ]


def build_cases() -> list[dict]:
    cases: list[dict] = []

    # ── 第 1 类：事实记忆（24）────────────────────────────
    # 0-7 easy（无噪声）/ 8-15 medium（3 条噪声）/ 16-23 hard（7 条噪声）
    for i, (fact, kw, imp, token, query) in enumerate(FACTS):
        if i < 8:
            difficulty, noise_n = "easy", 0
        elif i < 16:
            difficulty, noise_n = "medium", 3
        else:
            difficulty, noise_n = "hard", 7
        cases.append({
            "id": f"fact_{i + 1:03d}",
            "category": "fact_recall",
            "setup_turns": [{"fact": fact, "keywords": kw, "importance": imp}]
            + _noise(i, noise_n),
            "query": query,
            "expected": {"should_recall": True, "match_any": [token], "must_not_match": []},
            "difficulty": difficulty,
        })

    # ── 第 2 类：多轮上下文依赖（24）──────────────────────
    # 目标记忆前面隔着 20-25 条闲聊，考察长上下文下目标是否还能被召回。
    for i, (fact, kw, imp, token, query) in enumerate(FACTS):
        noise_n = 20 if i % 2 == 0 else 25
        difficulty = "medium" if noise_n == 20 else "hard"
        cases.append({
            "id": f"longctx_{i + 1:03d}",
            "category": "long_context",
            "setup_turns": [{"fact": fact, "keywords": kw, "importance": imp}]
            + _noise(i * 3 + 1, noise_n),
            "query": query,
            "expected": {"should_recall": True, "match_any": [token], "must_not_match": []},
            "difficulty": difficulty,
        })

    # ── 第 3 类：情感记忆（24）───────────────────────────
    for i, (fact, kw, imp, token, query) in enumerate(EMOTION_FACTS):
        difficulty = "easy" if i % 3 == 0 else ("medium" if i % 3 == 1 else "hard")
        noise_n = 0 if difficulty == "easy" else (3 if difficulty == "medium" else 6)
        cases.append({
            "id": f"emotion_{i + 1:03d}",
            "category": "emotion_memory",
            "setup_turns": [{"fact": fact, "keywords": kw, "importance": imp}]
            + _noise(i * 2, noise_n),
            "query": query,
            "expected": {"should_recall": True, "match_any": [token], "must_not_match": []},
            "difficulty": difficulty,
        })

    # ── 第 4 类：干扰项（24）─────────────────────────────
    for i, (t_fact, t_kw, t_imp, t_tok, d_fact, d_kw, d_imp, d_tok, query) in enumerate(DISTRACT):
        difficulty = "medium" if i % 2 == 0 else "hard"
        noise_n = 4 if difficulty == "medium" else 8
        cases.append({
            "id": f"distract_{i + 1:03d}",
            "category": "distractor",
            "setup_turns": [
                {"fact": t_fact, "keywords": t_kw, "importance": t_imp},
                {"fact": d_fact, "keywords": d_kw, "importance": d_imp},
            ] + _noise(i * 2 + 5, noise_n),
            "query": query,
            "expected": {
                "should_recall": True,
                "match_any": [t_tok],
                "must_not_match": [d_tok],
            },
            "difficulty": difficulty,
        })

    # ── 第 5 类：遗忘验证（24）───────────────────────────
    for i, (s_fact, s_kw, s_imp, f_fact, f_kw, f_imp, query, s_tok) in enumerate(FORGET):
        setup = [{"fact": s_fact, "keywords": s_kw, "importance": s_imp}]
        if f_fact:
            setup.append({"fact": f_fact, "keywords": f_kw, "importance": f_imp})
        n_noise = 4 if i % 2 == 0 else 8
        setup += _noise(i * 2 + 3, n_noise)
        cases.append({
            "id": f"forget_{i + 1:03d}",
            "category": "forgetting",
            "setup_turns": setup,
            "query": query,
            # 期望"已过期/已覆盖的信息不再被召回"——系统无此机制，预期整体失败。
            "expected": {"should_recall": False, "match_any": [s_tok], "must_not_match": []},
            "difficulty": "medium" if i % 2 == 0 else "hard",
        })

    return cases


def main():
    cases = build_cases()
    ids = [c["id"] for c in cases]
    assert len(cases) == len(set(ids)), "用例 id 重复"
    assert len(cases) == 120, f"用例数应为 120，实际 {len(cases)}"

    # importance 必须落在表约束内，否则 store_memory 的 INSERT 会直接失败
    for c in cases:
        for t in c["setup_turns"]:
            assert 1 <= t["importance"] <= 10, f"{c['id']} importance 越界: {t['importance']}"
            assert len(t["fact"]) <= 50, f"{c['id']} fact 超过 50 字: {t['fact']}"

    OUT.write_text(json.dumps(cases, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    from collections import Counter
    print(f"已写出 {OUT} —— {len(cases)} 条")
    for k, v in Counter(c["category"] for c in cases).items():
        print(f"  {k}: {v}")
    for k, v in Counter(c["difficulty"] for c in cases).items():
        print(f"  difficulty={k}: {v}")


if __name__ == "__main__":
    main()
